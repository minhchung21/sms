-- ===== テーブル定義 =====
CREATE TABLE SCHOOL (
    CD   CHARACTER(3) NOT NULL PRIMARY KEY,
    NAME CHARACTER VARYING(20)
);

CREATE TABLE TEACHER (
    ID        CHARACTER VARYING(10) NOT NULL PRIMARY KEY,
    PASSWORD  CHARACTER VARYING(30),
    NAME      CHARACTER VARYING(10),
    SCHOOL_CD CHARACTER(3)
);

CREATE TABLE CLASS_NUM (
    SCHOOL_CD CHARACTER(3) NOT NULL,
    CLASS_NUM CHARACTER VARYING(5) NOT NULL,
    PRIMARY KEY (SCHOOL_CD, CLASS_NUM)
);

CREATE TABLE SUBJECT (
    SCHOOL_CD CHARACTER(3) NOT NULL,
    CD        CHARACTER(3) NOT NULL,
    NAME      CHARACTER VARYING(20) NOT NULL,
    PRIMARY KEY (SCHOOL_CD, CD)
);

CREATE TABLE STUDENT (
    NO        CHARACTER VARYING(10) NOT NULL PRIMARY KEY,
    NAME      CHARACTER VARYING(10),
    ENT_YEAR  INTEGER,
    CLASS_NUM CHARACTER(3),
    IS_ATTEND BOOLEAN,
    SCHOOL_CD CHARACTER(3)
);

CREATE TABLE TEST (
    STUDENT_NO CHARACTER VARYING(10) NOT NULL,
    SUBJECT_CD CHARACTER(3) NOT NULL,
    SCHOOL_CD  CHARACTER(10) NOT NULL,
    NO         INTEGER NOT NULL,
    POINT      INTEGER,
    CLASS_NUM  CHARACTER VARYING(5),
    PRIMARY KEY (STUDENT_NO, SUBJECT_CD, SCHOOL_CD, NO)
);

CREATE TABLE ATTENDANCE (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_NO      CHARACTER VARYING(10) NOT NULL,
    SUBJECT_CD      CHARACTER VARYING(10) NOT NULL,
    ATTENDANCE_DATE DATE NOT NULL,
    STATUS          CHARACTER VARYING(20) NOT NULL,
    SCHOOL_CD       CHARACTER VARYING(20) NOT NULL
);

